std::vector<GeneratedFile> emit_cpu(const ir::Pattern& p, const std::string& stem) {
  CpuEmitter em(p);
  const std::string hdr = stem + ".hpp";
  std::vector<GeneratedFile> out;
  out.push_back({hdr, em.header(p.file)});
  out.push_back({stem + "_cpu.cpp", em.driver(p.file, hdr)});
  return out;
}

