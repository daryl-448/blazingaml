// The registry emitter (SPEC §7.6): registry.cpp, the table blz checks against the feature config
// at start-up (E402) and dispatches through.
#include <map>
#include <stdexcept>

#include "codegen/codegen.hpp"
#include "codegen/writer.hpp"

namespace blz::codegen {

namespace {

std::string quoted(const std::string& s) {
  std::string q = "\"";
  for (char c : s) {
    if (c == '"' || c == '\\') q += '\\';
    q += c;
  }
  return q + "\"";
}

}  // namespace

GeneratedFile emit_registry(const std::vector<ir::Pattern>& patterns, const std::vector<std::string>& stems,
                            const std::vector<Fusion>& fusions) {
  std::map<std::string, const ir::Pattern*> seen;
  for (const ir::Pattern& p : patterns) {
    auto [it, fresh] = seen.emplace(p.name, &p);
    if (!fresh)
      dsl::fail("E102", p.name_loc,
                "pattern '" + p.name + "' is already defined in " + dsl::format_loc(it->second->name_loc) +
                    "; pattern names are unique across the library");
  }
  Writer w;
  w.line("// generated by blzc from " + std::to_string(patterns.size()) + " pattern spec(s) — do not edit (SPEC §7.6)");
  w.line("#include \"blz/registry.hpp\"");
  w.line();
  for (const std::string& stem : stems) w.line("#include \"" + stem + ".hpp\"");
  w.line();
  w.line("// The CUDA launchers exist only in a build with BLZ_ENABLE_CUDA (SPEC §7.5).");
  w.line("#if defined(BLZ_WITH_CUDA)");
  w.line("#define BLZ_CUDA_FN(f) &f");
  w.line("#else");
  w.line("#define BLZ_CUDA_FN(f) nullptr");
  w.line("#endif");
  w.line();
  w.line("namespace blz {");
  w.line();
  if (!fusions.empty()) {
    w.line("// The fusions' launchers (fused_<id>_cuda.cu, SPEC v2 §8 S7).");
    w.line("namespace gen {");
    for (const Fusion& f : fusions) {
      w.line("void fused_" + f.id +
             "_cuda_bucket(const GraphView& g, const FusedParams& p, std::uint64_t first, std::uint32_t count, "
             "std::uint32_t threshold, std::uint8_t* flags, void* stream);");
      w.line("void fused_" + f.id + "_cuda(const GraphView& g, const FusedParams& p, const FusedRun& run);");
    }
    w.line("}  // namespace gen");
    w.line();
  }
  w.line("namespace {");
  w.line();
  for (const ir::Pattern& p : patterns) {
    if (p.consts.empty()) continue;
    std::string list;
    for (const auto& [k, v] : p.consts) list += (list.empty() ? "" : ", ") + std::string("{") + quoted(k) + ", " + std::to_string(v) + "}";
    w.line("constexpr ConstInfo kConsts_" + p.name + "[] = {" + list + "};");
  }
  w.line();
  w.open("constexpr PatternInfo kPatterns[] = {");
  for (const ir::Pattern& p : patterns) {
    const std::string consts = p.consts.empty() ? "{}" : "kConsts_" + p.name;
    const bool pinned = p.visibility_loc.line > 0;
    const std::string vis = !pinned ? "" : p.visibility == dsl::Visibility::stream ? "stream" : "timestamp";
    w.line("{" + quoted(p.name) + ", " + quoted(p.block) + ", " + quoted(dsl::format_loc(p.block_loc)) + ", " +
           quoted(p.file) + ", " + quoted(p.spec_sha256) + ", " + quoted(vis) + ", " +
           quoted(pinned ? dsl::format_loc(p.visibility_loc) : "") + ", " + quoted(p.span_param) + ", " + consts +
           ", &gen::" + p.name + "_cpu, &gen::" +
           p.name + "_work, BLZ_CUDA_FN(gen::" + p.name + "_cuda_bucket), BLZ_CUDA_FN(gen::" + p.name + "_cuda), " +
           (p.plan.sweep ? "true" : "false") + ", " + (p.plan.reach ? "true" : "false") + ", " +
           quoted(p.family == dsl::Family::clean ? "clean" : "legacy") + ", " + (p.one_instance ? "true" : "false") + "},");
  }
  w.close("};");
  // blzc --disable applies to the whole library (SPEC v2 §7.2).
  const std::vector<std::string> off = patterns.empty() ? std::vector<std::string>{} : ir::disabled_names(patterns[0].plan.opts);
  for (const ir::Pattern& p : patterns)
    if (ir::disabled_names(p.plan.opts) != off)
      throw std::runtime_error("the patterns of one registry were planned with different --disable lists");
  if (!off.empty()) {
    std::string list;
    for (const std::string& n : off) list += (list.empty() ? "" : ", ") + quoted(n);
    w.line();
    w.line("constexpr const char* kDisabled[] = {" + list + "};");
  }
  for (std::size_t i = 0; i < fusions.size(); ++i) {
    const Fusion& f = fusions[i];
    std::string members, slots;
    for (std::size_t k = 0; k < f.members.size(); ++k) {
      members += (k ? ", " : "") + std::string("&kPatterns[") + std::to_string(f.members[k]) + "]";
      slots += (k ? ", " : "") + std::to_string(f.slots[k]);
    }
    if (i == 0) w.line();
    w.line("constexpr const PatternInfo* kFusionMembers_" + std::to_string(i) + "[] = {" + members + "};");
    w.line("constexpr std::uint32_t kFusionSlots_" + std::to_string(i) + "[] = {" + slots + "};");
  }
  if (!fusions.empty()) {
    w.line();
    w.open("constexpr FusionInfo kFusions[] = {");
    for (std::size_t i = 0; i < fusions.size(); ++i) {
      const Fusion& f = fusions[i];
      const std::string n = std::to_string(i);
      w.line("{" + quoted(f.name) + ", kFusionMembers_" + n + ", kFusionSlots_" + n + ", BLZ_CUDA_FN(gen::fused_" +
             f.id + "_cuda_bucket), BLZ_CUDA_FN(gen::fused_" + f.id + "_cuda)},");
    }
    w.close("};");
  }
  w.line();
  w.line("}  // namespace");
  w.line();
  w.line("std::span<const PatternInfo> registered_patterns() { return kPatterns; }");
  w.line();
  w.line(fusions.empty() ? "std::span<const FusionInfo> registered_fusions() { return {}; }"
                         : "std::span<const FusionInfo> registered_fusions() { return kFusions; }");
  w.line();
  w.line(off.empty() ? "std::span<const char* const> disabled_optimizations() { return {}; }"
                     : "std::span<const char* const> disabled_optimizations() { return kDisabled; }");
  w.line();
  w.line("}  // namespace blz");
  return {"registry.cpp", w.str()};
}

}  // namespace blz::codegen
