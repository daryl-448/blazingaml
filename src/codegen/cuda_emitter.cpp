// The CUDA emitter (SPEC §7.5): <stem>_cuda.cu. The light kernel runs <pattern>_trigger from
// <stem>.hpp, the very text the OpenMP driver runs; the heavy kernel runs <pattern>_trigger_warp,
// which cpu_emitter.cpp derives from the same plan in warp mode. The kernels, the bucketing
// kernel and the launch code are the templates of include/blz/cuda_kernels.cuh.
#include "codegen/codegen.hpp"
#include "codegen/writer.hpp"

namespace blz::codegen {

GeneratedFile emit_cuda(const ir::Pattern& p, const std::string& stem) {
  const std::string warp = detail::warp_trigger_fn(p);  // throws E501 like emit_cpu
  const std::string k = p.name + "_kernels";
  Writer w;
  w.line("// generated by blzc from " + p.file + " — do not edit (SPEC §7.5)");
  w.line("// pattern " + p.name + ", block " + p.block + ": light kernel = " + p.name +
         "_trigger (thread per trigger), heavy kernel = " + p.name + "_trigger_warp (warp per trigger)");
  w.line("#include \"" + stem + ".hpp\"");
  w.line("#include \"blz/cuda_kernels.cuh\"");
  w.line();
  w.line("namespace blz::gen {");
  w.line();
  w.raw(warp);
  w.line();
  w.line("// The pattern's bodies, as include/blz/cuda_kernels.cuh expects them.");
  w.open("struct " + k + " {");
  w.line("template <class Sink>");
  w.open("__device__ static void trigger(const GraphView& g, const Params& p, std::uint32_t e, Sink& out) {");
  w.line(p.name + "_trigger(g, p, e, out);");
  w.close();
  w.line("template <class Sink>");
  w.open("__device__ static void warp(const GraphView& g, const Params& p, std::uint32_t e, std::uint32_t lane, Sink& out) {");
  w.line(p.name + "_trigger_warp(g, p, e, lane, out);");
  w.close();
  w.open("__device__ static std::uint32_t work(const GraphView& g, const Params& p, std::uint32_t e) {");
  w.line("return " + p.name + "_work(g, p, e);");
  w.close();
  w.close("};");
  w.line();
  w.open("void " + p.name +
         "_cuda_bucket(const GraphView& g, const Params& p, std::uint64_t first, std::uint32_t count, "
         "std::uint32_t threshold, std::uint8_t* flags, void* stream) {");
  w.line("cuda::launch_bucket<" + k + ">(g, p, first, count, threshold, flags, stream);");
  w.close();
  w.line();
  w.open("void " + p.name + "_cuda(const GraphView& g, const Params& p, const CudaRun& run) {");
  w.line("cuda::launch<" + k + ">(g, p, run);");
  w.close();
  w.line();
  w.line("}  // namespace blz::gen");
  return {stem + "_cuda.cu", w.str()};
}

}  // namespace blz::codegen
